/**
 * Кто выбрал машину - карта или правая область.
 *
 * Нужно ровно для одного правила: карта перелетает к треку машины, только если ее выбрали
 * в списке справа (раздел 7 этапа, п. 5). Выбор кликом по самой карте перелета не вызывает -
 * машина и так под курсором, и уезжающая из-под пальца карта читалась бы как сбой.
 *
 * Флаг, а не поле стора: это не состояние экрана, его незачем ни хранить, ни класть в адрес,
 * ни синхронизировать между областями.
 */

let selectedByMap = false;

export function markSelectionFromMap(): void {
  selectedByMap = true;
}

/** Читает и сбрасывает флаг: каждый выбор учитывается ровно один раз. */
export function takeSelectionFromMap(): boolean {
  const value = selectedByMap;
  selectedByMap = false;
  return value;
}
