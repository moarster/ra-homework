/**
 * Правило аварии "нет данных" - одно на всю область карты.
 *
 * Вынесено в отдельный модуль без зависимостей намеренно: правило нужно и циклу отрисовки
 * (серая машина в красном кольце), и всплывашке (время последней передачи, ФИО и телефон
 * водителя). Пока определений было два - в рендерере по статусу, во всплывашке по возрасту -
 * машина могла оказаться в красном кольце без объяснения, почему.
 */

import { APP_CONFIG, type VehicleSnapshot } from '@ra/contracts';

/** Порог аварии "нет данных" в секундах: из конфигурации, а не числом в коде. */
export const NO_DATA_SECONDS = APP_CONFIG.noDataAlarmMinutes * 60;

/**
 * Активна ли авария "нет данных".
 *
 * Считается по возрасту последней точки, а не по статусу `NO_DATA`: статус сервер ставит уже
 * через несколько минут молчания, а красное кольцо по разделу 5 этапа означает именно аварию,
 * то есть отсутствие данных дольше сорока минут. Машина, замолчавшая минуту назад, и так
 * серая - у ее снапшота светофор "нет данных".
 */
export function isNoDataAlarm(snapshot: VehicleSnapshot | undefined): boolean {
  return snapshot !== undefined && snapshot.age >= NO_DATA_SECONDS;
}
